exports.down = async (pgm) => {
  // Откат: восстанавливаем как current предыдущую (последнюю по version,
  // не v2-revert) и удаляем v2-revert. Если предыдущей не было — оставляем
  // как есть (UPDATE без подходящих строк = no-op).
  for (const agentType of ["curator_chat", "narrative_brief", "program_analytics"]) {
    const shortId = { curator_chat: "cc", narrative_brief: "nb", program_analytics: "pa" }[
      agentType
    ];
    pgm.sql(`
      UPDATE agent_prompts SET is_current = true
        WHERE id = (
          SELECT id FROM agent_prompts
          WHERE agent_type = '${agentType}' AND id <> 'agent-prompt-${shortId}-v2-revert'
          ORDER BY version DESC
          LIMIT 1
        );
    `);
    pgm.sql(`DELETE FROM agent_prompts WHERE id = 'agent-prompt-${shortId}-v2-revert';`);
  }
};
